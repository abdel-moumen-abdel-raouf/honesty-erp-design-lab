import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const ROOT = process.cwd();
const COLORS_ROOT = path.join(
  ROOT,
  'src',
  'styles',
  'foundation',
  'reference',
  'colors',
);
const OUTPUT_FILE = path.join(
  ROOT,
  'src',
  'app',
  'foundation',
  'colors',
  'system-color-registry.ts',
);

const FAMILIES = [
  'neutral',
  'primary',
  'secondary',
  'accent',
  'green',
  'amber',
  'red',
  'cyan',
];
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

function parsePaletteSource(family, source, label) {
  if (!FAMILIES.includes(family)) {
    throw new Error(`${label}: unsupported system color family "${family}"`);
  }

  const declarations = [
    ...source.matchAll(
      /\$honesty-ref-color-([a-z]+)-(\d+)\s*:\s*(#[0-9a-fA-F]{6})\s*;/g,
    ),
  ];
  const colors = {};

  for (const match of declarations) {
    const declarationFamily = match[1];
    const step = Number(match[2]);

    if (declarationFamily !== family) {
      throw new Error(
        `${label}: unsupported family declaration "${declarationFamily}"`,
      );
    }

    if (!STEPS.includes(step)) {
      throw new Error(`${label}: unsupported step "${step}"`);
    }

    if (colors[step] !== undefined) {
      throw new Error(`${label}: duplicate step "${step}"`);
    }

    colors[step] = match[3].toUpperCase();
  }

  for (const step of STEPS) {
    if (colors[step] === undefined) {
      throw new Error(
        `${label}: missing $honesty-ref-color-${family}-${step}`,
      );
    }
  }

  if (Object.keys(colors).length !== STEPS.length) {
    throw new Error(`${label}: unexpected system color declaration count`);
  }

  return colors;
}

function readPalettes() {
  return Object.fromEntries(
    FAMILIES.map((family) => {
      const file = path.join(COLORS_ROOT, `_${family}.scss`);
      const source = fs.readFileSync(file, 'utf8');
      return [family, parsePaletteSource(family, source, file)];
    }),
  );
}

function buildRegistrySource(palettes) {
  const paletteLines = FAMILIES.map((family) => {
    const steps = STEPS.map(
      (step) => `    ${step}: '${palettes[family][step]}',`,
    ).join('\n');
    return `  ${family}: {\n${steps}\n  },`;
  }).join('\n');

  return `// Generated by tools/foundation/generate-system-color-registry.mjs.\n// Do not edit manually.\n\nexport const ERP_SYSTEM_COLOR_FAMILIES = [\n${FAMILIES.map((family) => `  '${family}',`).join('\n')}\n] as const;\n\nexport const ERP_SYSTEM_COLOR_STEPS = [\n  ${STEPS.join(', ')}\n] as const;\n\nexport type ErpSystemColorFamily =\n  (typeof ERP_SYSTEM_COLOR_FAMILIES)[number];\n\nexport type ErpSystemColorStep =\n  (typeof ERP_SYSTEM_COLOR_STEPS)[number];\n\nexport type ErpSystemColorToken =\n  \`\${ErpSystemColorFamily}-\${ErpSystemColorStep}\`;\n\nexport const ERP_SYSTEM_COLOR_PALETTES = {\n${paletteLines}\n} as const satisfies Readonly<\n  Record<ErpSystemColorFamily, Readonly<Record<ErpSystemColorStep, string>>>\n>;\n\nexport function resolveErpSystemColorToken(\n  token: ErpSystemColorToken,\n): string {\n  const separator = token.lastIndexOf('-');\n  const family = token.slice(0, separator) as ErpSystemColorFamily;\n  const step = Number(token.slice(separator + 1)) as ErpSystemColorStep;\n\n  return ERP_SYSTEM_COLOR_PALETTES[family][step];\n}\n`;
}

function validateCurrentRegistry(current, expected, label) {
  if (current !== expected) {
    throw new Error(`${label}: generated registry is stale`);
  }
}

function validFixture(family = 'neutral') {
  return STEPS.map(
    (step, index) =>
      `$honesty-ref-color-${family}-${step}: #${String(index + 1).padStart(6, '0')};`,
  ).join('\n');
}

function runSelfTest() {
  const parsed = parsePaletteSource(
    'neutral',
    validFixture(),
    'valid fixture',
  );

  if (parsed[50] !== '#000001' || parsed[950] !== '#000011') {
    throw new Error('System color generator rejected valid fixture values');
  }

  const invalidFixtures = [
    validFixture().replace(
      '$honesty-ref-color-neutral-50: #000001;\n',
      '',
    ),
    `${validFixture()}\n$honesty-ref-color-neutral-975: #123456;`,
    validFixture().replace(
      '$honesty-ref-color-neutral-50',
      '$honesty-ref-color-primary-50',
    ),
  ];

  for (const [index, fixture] of invalidFixtures.entries()) {
    let rejected = false;

    try {
      const palette = parsePaletteSource(
        'neutral',
        fixture,
        `invalid fixture ${index + 1}`,
      );
      buildRegistrySource({
        neutral: palette,
        primary: palette,
        secondary: palette,
        accent: palette,
        green: palette,
        amber: palette,
        red: palette,
        cyan: palette,
      });

    } catch {
      rejected = true;
    }

    if (!rejected) {
      throw new Error(
        `System color generator accepted invalid fixture ${index + 1}`,
      );
    }
  }

  const validPalettes = Object.fromEntries(
    FAMILIES.map((family) => [family, parsed]),
  );
  const expectedRegistry = buildRegistrySource(validPalettes);
  let staleRejected = false;

  try {
    validateCurrentRegistry(
      expectedRegistry.replace('#000001', '#ABCDEF'),
      expectedRegistry,
      'stale fixture',
    );
  } catch {
    staleRejected = true;
  }

  if (!staleRejected) {
    throw new Error('System color generator accepted stale generated value');
  }

  const tokenPattern = new RegExp(
    `^(?:${FAMILIES.join('|')})-(?:${STEPS.join('|')})$`,
  );

  if (tokenPattern.test('primary-500-extra')) {
    throw new Error('System color generator accepted malformed token fixture');
  }

  console.log('System color registry generator self-test passed.');
}

if (process.argv.includes('--self-test')) {
  runSelfTest();
  process.exit(0);
}

const generated = buildRegistrySource(readPalettes());

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT_FILE)
    ? fs.readFileSync(OUTPUT_FILE, 'utf8')
    : '';

  try {
    validateCurrentRegistry(current, generated, OUTPUT_FILE);
  } catch {
    console.error(
      'System color registry is stale. Run npm run system-colors:generate.',
    );
    process.exit(1);
  }

  console.log(
    `System color registry is current (${FAMILIES.length} families, ${STEPS.length} steps).`,
  );
  process.exit(0);
}

fs.writeFileSync(OUTPUT_FILE, generated, 'utf8');
console.log(
  `Generated system color registry (${FAMILIES.length} families, ${STEPS.length} steps).`,
);
